-- Zero-copy cloning examples: table, schema, database, and Time Travel clones
-- Co-authored with CoCo

CREATE DATABASE IF NOT EXISTS CLONE_DEMO_DB;
CREATE SCHEMA IF NOT EXISTS CLONE_DEMO_DB.SALES;

-- 1. Source table with sample data
CREATE OR REPLACE TABLE CLONE_DEMO_DB.SALES.ORDERS (
    ORDER_ID NUMBER,
    CUSTOMER VARCHAR(50),
    AMOUNT NUMBER(10,2)
);
INSERT INTO CLONE_DEMO_DB.SALES.ORDERS VALUES (1,'Alice',100),(2,'Bob',250),(3,'Carol',75);




-- 2. Clone a table (no extra storage until data diverges)
CREATE OR REPLACE TABLE CLONE_DEMO_DB.SALES.ORDERS_CLONE CLONE CLONE_DEMO_DB.SALES.ORDERS;
SELECT * FROM CLONE_DEMO_DB.SALES.ORDERS_CLONE;



-- 3. Changes to the clone do not affect the source (and vice versa)
UPDATE CLONE_DEMO_DB.SALES.ORDERS_CLONE SET AMOUNT = 999 WHERE ORDER_ID = 1;
INSERT INTO CLONE_DEMO_DB.SALES.ORDERS VALUES (4,'Dave',500);

SELECT 'SOURCE' AS TBL, * FROM CLONE_DEMO_DB.SALES.ORDERS
UNION ALL
SELECT 'CLONE', * FROM CLONE_DEMO_DB.SALES.ORDERS_CLONE
ORDER BY TBL, ORDER_ID;



-- 4. Clone a whole schema (all tables inside are cloned)
CREATE OR REPLACE SCHEMA CLONE_DEMO_DB.SALES_DEV CLONE CLONE_DEMO_DB.SALES;
SHOW TABLES IN SCHEMA CLONE_DEMO_DB.SALES_DEV;



-- 5. Clone an entire database (e.g. for a dev/test environment)
CREATE OR REPLACE DATABASE CLONE_DEMO_DB_DEV CLONE CLONE_DEMO_DB;
SHOW SCHEMAS IN DATABASE CLONE_DEMO_DB_DEV;


-- 6. Clone at a point in time (Time Travel): table as it was 1 minute ago
CREATE OR REPLACE TABLE CLONE_DEMO_DB.SALES.ORDERS_1MIN_AGO
    CLONE CLONE_DEMO_DB.SALES.ORDERS AT (OFFSET => -60);


-- 7. Recover from a bad change: clone from before a DELETE using a query ID
DELETE FROM CLONE_DEMO_DB.SALES.ORDERS WHERE ORDER_ID = 2;
SET bad_qid = LAST_QUERY_ID();
CREATE OR REPLACE TABLE CLONE_DEMO_DB.SALES.ORDERS_RESTORED
    CLONE CLONE_DEMO_DB.SALES.ORDERS BEFORE (STATEMENT => $bad_qid);
SELECT * FROM CLONE_DEMO_DB.SALES.ORDERS_RESTORED;


-- 8. Compare storage: clones share micro-partitions until they diverge
SELECT TABLE_NAME, ROW_COUNT, ACTIVE_BYTES, CLONE_GROUP_ID
FROM CLONE_DEMO_DB.INFORMATION_SCHEMA.TABLE_STORAGE_METRICS
WHERE TABLE_SCHEMA = 'SALES';


-- 9. Cleanup
DROP DATABASE IF EXISTS CLONE_DEMO_DB_DEV;
DROP DATABASE IF EXISTS CLONE_DEMO_DB;
