-- Definition: Zero-Copy Cloning is a Snowflake feature that creates a copy of an existing table, schema, or database without initially duplicating its underlying data storage.


-- 1)Create a table clone

-- 1)CREATE A TABLE CLONE
CREATE TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_CLONE
CLONE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11;



-- 2)VERIFY CLONED DATA
SELECT *
FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_CLONE;



-- 3)CHANGES
UPDATE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_CLONE
SET SALARY = 60000
WHERE ID = 2;


-- NOW CHECK THE CLONE
SELECT *
FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_CLONE
WHERE ID = 2;


-- CHECK THE ORIGINAL CLONE

SELECT *
FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11
WHERE ID = 2;

-- Cloning schema
CREATE SCHEMA COMPANY_DBS.EMPLOYEE_SCHEMA_CLONE
CLONE COMPANY_DBS.EMPLOYEE_SCHEMA;


-- CHECK
SHOW SCHEMAS IN DATABASE COMPANY_DBS;


-- CLONING DATABASES
CREATE DATABASE COMPANY_DBS_CLONE
CLONE COMPANY_DBS;

-- CHECK
SHOW DATABASES LIKE 'COMPANY_DBS%';



-- ===================== MORE EXAMPLES =====================

-- 4) CLONE A TABLE AS IT WAS IN THE PAST (Clone + Time Travel)
CREATE OR REPLACE TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_10MIN_AGO
CLONE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11
AT (OFFSET => -60*10);          -- table as it was 10 minutes ago

CREATE OR REPLACE TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_BEFORE_OVERWRITE
CLONE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11
BEFORE (STATEMENT => '01c87756-0002-5594-000f-fa920016a77e');  -- just before a specific query


-- 5) CLONE AND ORIGINAL ARE INDEPENDENT: DELETE IN CLONE ONLY
DELETE FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_CLONE
WHERE DEPARTMENT = 'Sales';

SELECT 'ORIGINAL' AS SRC, COUNT(*) AS ROWS_CNT FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11
UNION ALL
SELECT 'CLONE', COUNT(*) FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_CLONE;


-- 6) COMPARE ORIGINAL VS CLONE (rows that differ)
SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11
MINUS
SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_CLONE;


-- 7) INSERT NEW ROW IN CLONE (original is not affected)
INSERT INTO COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_CLONE
VALUES (100, 'TestUser', 'QA', 30000);

SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11 WHERE ID = 100;        -- 0 rows
SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_CLONE WHERE ID = 100;  -- 1 row


-- 8) USE A CLONE AS A SAFE BACKUP BEFORE RISKY CHANGES
