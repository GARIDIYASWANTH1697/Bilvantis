-- 11) SEE CLONE INFO (CLONE_GROUP_ID shows tables sharing storage)
SELECT TABLE_NAME, ID, CLONE_GROUP_ID, ACTIVE_BYTES
FROM COMPANY_DBS.INFORMATION_SCHEMA.TABLE_STORAGE_METRICS
WHERE TABLE_SCHEMA = 'EMPLOYEE_SCHEMA'
  AND TABLE_NAME LIKE 'EMPLOYEES11%';


