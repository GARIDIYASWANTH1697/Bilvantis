-- Examples of COPY INTO (load, unload, validate, and common options) in Snowflake
-- Co-authored with CoCo

-- Setup: replace MY_DB.MY_SCHEMA with your own database and schema
CREATE STAGE IF NOT EXISTS MY_DB.MY_SCHEMA.MY_STAGE;

CREATE FILE FORMAT IF NOT EXISTS MY_DB.MY_SCHEMA.CSV_FF
  TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = ('', 'NULL');

CREATE FILE FORMAT IF NOT EXISTS MY_DB.MY_SCHEMA.JSON_FF TYPE = JSON STRIP_OUTER_ARRAY = TRUE;
CREATE FILE FORMAT IF NOT EXISTS MY_DB.MY_SCHEMA.PARQUET_FF TYPE = PARQUET;

CREATE TABLE IF NOT EXISTS MY_DB.MY_SCHEMA.CUSTOMERS (ID NUMBER, NAME STRING, EMAIL STRING, CREATED_AT TIMESTAMP_NTZ);
CREATE TABLE IF NOT EXISTS MY_DB.MY_SCHEMA.RAW_EVENTS (V VARIANT);

-- 1. Basic CSV load from a stage
COPY INTO MY_DB.MY_SCHEMA.CUSTOMERS
FROM @MY_DB.MY_SCHEMA.MY_STAGE/customers/
FILE_FORMAT = (FORMAT_NAME = 'MY_DB.MY_SCHEMA.CSV_FF');

-- 2. Load specific files
COPY INTO MY_DB.MY_SCHEMA.CUSTOMERS
FROM @MY_DB.MY_SCHEMA.MY_STAGE
FILES = ('customers_1.csv', 'customers_2.csv')
FILE_FORMAT = (FORMAT_NAME = 'MY_DB.MY_SCHEMA.CSV_FF');

-- 3. Load files matching a pattern
COPY INTO MY_DB.MY_SCHEMA.CUSTOMERS
FROM @MY_DB.MY_SCHEMA.MY_STAGE
PATTERN = '.*customers_[0-9]+[.]csv'
FILE_FORMAT = (FORMAT_NAME = 'MY_DB.MY_SCHEMA.CSV_FF');

-- 4. Skip bad rows instead of aborting
COPY INTO MY_DB.MY_SCHEMA.CUSTOMERS
FROM @MY_DB.MY_SCHEMA.MY_STAGE/customers/
FILE_FORMAT = (FORMAT_NAME = 'MY_DB.MY_SCHEMA.CSV_FF')
ON_ERROR = 'CONTINUE';

-- 5. Dry run: validate without loading
COPY INTO MY_DB.MY_SCHEMA.CUSTOMERS
FROM @MY_DB.MY_SCHEMA.MY_STAGE/customers/
FILE_FORMAT = (FORMAT_NAME = 'MY_DB.MY_SCHEMA.CSV_FF')
VALIDATION_MODE = 'RETURN_ERRORS';

-- 6. Transform during load (column reordering, casting, metadata)
COPY INTO MY_DB.MY_SCHEMA.CUSTOMERS (ID, NAME, EMAIL, CREATED_AT)
FROM (
  SELECT $1::NUMBER, UPPER($2), LOWER($3), CURRENT_TIMESTAMP()
  FROM @MY_DB.MY_SCHEMA.MY_STAGE/customers/
)
FILE_FORMAT = (FORMAT_NAME = 'MY_DB.MY_SCHEMA.CSV_FF');

-- 7. Load JSON into a VARIANT column
COPY INTO MY_DB.MY_SCHEMA.RAW_EVENTS
FROM @MY_DB.MY_SCHEMA.MY_STAGE/events/
FILE_FORMAT = (FORMAT_NAME = 'MY_DB.MY_SCHEMA.JSON_FF');

-- 8. Load Parquet matching columns by name
COPY INTO MY_DB.MY_SCHEMA.CUSTOMERS
FROM @MY_DB.MY_SCHEMA.MY_STAGE/parquet/
FILE_FORMAT = (FORMAT_NAME = 'MY_DB.MY_SCHEMA.PARQUET_FF')
MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

-- 9. Force reload and purge files after a successful load
COPY INTO MY_DB.MY_SCHEMA.CUSTOMERS
FROM @MY_DB.MY_SCHEMA.MY_STAGE/customers/
FILE_FORMAT = (FORMAT_NAME = 'MY_DB.MY_SCHEMA.CSV_FF')
FORCE = TRUE
PURGE = TRUE;

-- 10. Unload a table to CSV (gzip) with a header
COPY INTO @MY_DB.MY_SCHEMA.MY_STAGE/export/customers_
FROM MY_DB.MY_SCHEMA.CUSTOMERS
FILE_FORMAT = (TYPE = CSV COMPRESSION = GZIP FIELD_OPTIONALLY_ENCLOSED_BY = '"')
HEADER = TRUE
OVERWRITE = TRUE;

-- 11. Unload a query result to Parquet as a single file
COPY INTO @MY_DB.MY_SCHEMA.MY_STAGE/export/recent.parquet
FROM (SELECT ID, NAME FROM MY_DB.MY_SCHEMA.CUSTOMERS WHERE CREATED_AT >= DATEADD(day, -7, CURRENT_TIMESTAMP()))
FILE_FORMAT = (TYPE = PARQUET)
SINGLE = TRUE
OVERWRITE = TRUE;

-- 12. Unload partitioned by date
COPY INTO @MY_DB.MY_SCHEMA.MY_STAGE/export/by_day/
FROM (SELECT ID, NAME, CREATED_AT FROM MY_DB.MY_SCHEMA.CUSTOMERS)
PARTITION BY ('date=' || TO_VARCHAR(CREATED_AT::DATE))
FILE_FORMAT = (TYPE = PARQUET)
MAX_FILE_SIZE = 104857600;

-- 13. Check load results
SELECT * FROM TABLE(MY_DB.INFORMATION_SCHEMA.COPY_HISTORY(
  TABLE_NAME => 'CUSTOMERS',
  START_TIME => DATEADD(hour, -24, CURRENT_TIMESTAMP())));
