-- Create source table

CREATE OR REPLACE TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_SOURCE (
    ID INT,
    NAME VARCHAR,
    DEPARTMENT VARCHAR,
    SALARY NUMBER
);

-- insert intial data

INSERT INTO COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_SOURCE
VALUES
(101, 'Ravi', 'IT', 25000),
(102, 'Rahul', 'HR', 30000);


-- create Target table
CREATE OR REPLACE TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_TARGET AS
SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_SOURCE;


-- Step-3 Create stream
CREATE OR REPLACE STREAM COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_STREAM
ON TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_SOURCE;


-- Update the source table
UPDATE COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_SOURCE
SET SALARY = 35000
WHERE ID = 101;


-- check
SELECT *
FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_STREAM;


-- Apply SCD type-1 using  merge

MERGE INTO COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_TARGET T
USING (
    SELECT *
    FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_STREAM
    WHERE METADATA$ACTION = 'INSERT'
) S
ON T.ID = S.ID

WHEN MATCHED THEN
    UPDATE SET
        T.NAME = S.NAME,
        T.DEPARTMENT = S.DEPARTMENT,
        T.SALARY = S.SALARY

WHEN NOT MATCHED THEN
    INSERT (ID, NAME, DEPARTMENT, SALARY)
    VALUES (S.ID, S.NAME, S.DEPARTMENT, S.SALARY);



-- Check the Target table

   SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_TARGET; 


-- Step 0: Add SCD-2 tracking columns (missing from EMP_TARGET)
ALTER TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_TARGET ADD COLUMN
    START_DATE DATE,
    END_DATE DATE,
    IS_CURRENT BOOLEAN;

UPDATE COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_TARGET
SET START_DATE = COALESCE(START_DATE, CURRENT_DATE()),
    IS_CURRENT = COALESCE(IS_CURRENT, TRUE);

-- Step 1: Expire the old version
UPDATE COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_TARGET
SET IS_CURRENT = FALSE,
    END_DATE = CURRENT_DATE()
WHERE ID = 101
  AND IS_CURRENT = TRUE;

-- Step 2: Insert the new version
INSERT INTO COMPANY_DBS.EMPLOYEE_SCHEMA.EMP_TARGET
    (ID, NAME, SALARY, START_DATE, END_DATE, IS_CURRENT)
VALUES
    (101, 'Ravi', 35000, CURRENT_DATE(), NULL, TRUE);