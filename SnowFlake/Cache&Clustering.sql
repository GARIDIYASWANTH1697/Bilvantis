-- =====================================================
-- CACHING EXAMPLES
-- =====================================================

-- 1. RESULT CACHE: run the same query twice. The 2nd run returns instantly
--    from the result cache (no warehouse compute) if data hasn't changed.
ALTER SESSION SET USE_CACHED_RESULT = TRUE;

SELECT DEPARTMENT, COUNT(*) AS EMP_COUNT, AVG(SALARY) AS AVG_SALARY
FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11
GROUP BY DEPARTMENT;

SELECT DEPARTMENT, COUNT(*) AS EMP_COUNT, AVG(SALARY) AS AVG_SALARY
FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11
GROUP BY DEPARTMENT;   -- check Query Profile: "QUERY RESULT REUSE"

-- 2. Reuse the last result without re-running the query
SELECT * FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE AVG_SALARY > 50000;

-- 3. Disable result cache to test the WAREHOUSE (local disk) cache
ALTER SESSION SET USE_CACHED_RESULT = FALSE;

SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11 WHERE SALARY > 40000;
-- Run again: Query Profile shows "Percentage scanned from cache" > 0%

-- 4. METADATA CACHE: answered from metadata, no data scan needed
SELECT COUNT(*), MIN(ID), MAX(ID) FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11;

-- Re-enable result cache
ALTER SESSION SET USE_CACHED_RESULT = TRUE;

-- Compare cache usage of recent queries
SELECT QUERY_ID, QUERY_TEXT, TOTAL_ELAPSED_TIME, BYTES_SCANNED,
       PERCENTAGE_SCANNED_FROM_CACHE
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY   -- may lag up to ~45 min
WHERE QUERY_TEXT ILIKE '%EMPLOYEES11%'
ORDER BY START_TIME DESC
LIMIT 10;

-- =====================================================
-- CLUSTERING EXAMPLES
-- =====================================================

-- 5. Check how well the table is clustered on candidate columns
SELECT SYSTEM$CLUSTERING_INFORMATION('COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11', '(SALARY)');
SELECT SYSTEM$CLUSTERING_DEPTH('COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11', '(DEPARTMENT)');

-- 6. Multi-column clustering key (low-cardinality column first)
ALTER TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11 CLUSTER BY (DEPARTMENT, SALARY);

-- 7. Query that benefits from pruning on the clustering key
SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11
WHERE DEPARTMENT = 'IT' AND SALARY BETWEEN 50000 AND 80000;
-- Query Profile: compare "Partitions scanned" vs "Partitions total"

-- 8. Pause / resume automatic clustering
ALTER TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11 SUSPEND RECLUSTER;
ALTER TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11 RESUME RECLUSTER;

