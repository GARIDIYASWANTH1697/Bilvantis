CREATE TASK COMPANY_DBS.EMPLOYEE_SCHEMA.MONTHLY_TASK
WAREHOUSE = COMPUTE_WH
SCHEDULE = 'USING CRON 4 * * * * Asia/Kolkata'
AS
INSERT INTO EMPLOYEE_BACKUP
SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11;


ALTER TASK COMPANY_DBS.EMPLOYEE_SCHEMA.MONTHLY_TASK RESUME;

-- Check Task status
SHOW TASKS;

-- Check EXECUTION history
SELECT *
FROM TABLE(COMPANY_DBS.INFORMATION_SCHEMA.TASK_HISTORY(TASK_NAME => 'MONTHLY_TASK'))
ORDER BY SCHEDULED_TIME DESC;


select * from COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11;


-- create backup table
CREATE TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEE_BACKUP
AS
SELECT *
FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11
WHERE 1 = 0;

-- step-3 Create a  Task
CREATE OR REPLACE TASK COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEE_LOAD_TASK
WAREHOUSE = COMPUTE_WH
SCHEDULE = '4 MINUTE'
AS
INSERT INTO COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEE_BACKUP
SELECT *
FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11;

-- step-4 Resume the Task
ALTER TASK COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEE_LOAD_TASK RESUME;


-- step-5 Executive history
SELECT *
FROM TABLE(COMPANY_DBS.INFORMATION_SCHEMA.TASK_HISTORY())
WHERE NAME = 'EMPLOYEE_LOAD_TASK'
ORDER BY SCHEDULED_TIME DESC;

-- step-6 check the backup table
SELECT *
FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEE_BACKUP;


-- stop the backup-table
ALTER TASK COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEE_LOAD_TASK
SUSPEND;