-- =====================================================
-- SNOWFLAKE ARCHITECTURE EXAMPLES
-- Layer 1: Cloud Services (metadata, security, optimization)
-- Layer 2: Compute (virtual warehouses)
-- Layer 3: Storage (micro-partitioned columnar storage)
-- =====================================================

-- ---------- CLOUD SERVICES LAYER: Security / RBAC ----------
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS ANALYST_ROLE;
CREATE ROLE IF NOT EXISTS ETL_ROLE;
GRANT ROLE ANALYST_ROLE TO ROLE SYSADMIN;
GRANT ROLE ETL_ROLE TO ROLE SYSADMIN;




-- ---------- COMPUTE LAYER: Separate warehouses per workload ----------
CREATE WAREHOUSE IF NOT EXISTS ETL_WH
  WAREHOUSE_SIZE = 'SMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE COMMENT = 'Data loading workloads';





-- Multi-cluster settings require Enterprise edition; remove those 3 options on Standard
CREATE WAREHOUSE IF NOT EXISTS BI_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  MIN_CLUSTER_COUNT = 1 MAX_CLUSTER_COUNT = 3 SCALING_POLICY = 'STANDARD'
  INITIALLY_SUSPENDED = TRUE COMMENT = 'BI / reporting concurrency';

GRANT USAGE ON WAREHOUSE ETL_WH TO ROLE ETL_ROLE;
GRANT USAGE ON WAREHOUSE BI_WH  TO ROLE ANALYST_ROLE;



-- ---------- STORAGE LAYER: Database / schema / tables ----------
CREATE DATABASE IF NOT EXISTS ARCH_DEMO_DB;
CREATE SCHEMA IF NOT EXISTS ARCH_DEMO_DB.RAW;
CREATE SCHEMA IF NOT EXISTS ARCH_DEMO_DB.CURATED;

CREATE OR REPLACE TABLE ARCH_DEMO_DB.RAW.ORDERS (
  ORDER_ID NUMBER, CUSTOMER_ID NUMBER, ORDER_DATE DATE,
  AMOUNT NUMBER(10,2), REGION STRING
) DATA_RETENTION_TIME_IN_DAYS = 1;   -- Time Travel

USE WAREHOUSE ETL_WH;
INSERT INTO ARCH_DEMO_DB.RAW.ORDERS
SELECT SEQ4(), UNIFORM(1,1000,RANDOM()), DATEADD(DAY,-UNIFORM(0,365,RANDOM()),CURRENT_DATE()),
       UNIFORM(10,500,RANDOM()), ARRAY_CONSTRUCT('NA','EU','APAC')[UNIFORM(0,2,RANDOM())]::STRING
FROM TABLE(GENERATOR(ROWCOUNT => 10000));




-- Clustering key (micro-partition pruning)
ALTER TABLE ARCH_DEMO_DB.RAW.ORDERS CLUSTER BY (ORDER_DATE);



-- Zero-copy clone (metadata-only, shares storage)
CREATE OR REPLACE TABLE ARCH_DEMO_DB.CURATED.ORDERS_DEV CLONE ARCH_DEMO_DB.RAW.ORDERS;




-- Curated view for BI
CREATE OR REPLACE VIEW ARCH_DEMO_DB.CURATED.SALES_BY_REGION AS
SELECT REGION, DATE_TRUNC('MONTH', ORDER_DATE) AS MONTH, SUM(AMOUNT) AS REVENUE
FROM ARCH_DEMO_DB.RAW.ORDERS GROUP BY 1, 2;

GRANT USAGE ON DATABASE ARCH_DEMO_DB TO ROLE ANALYST_ROLE;
GRANT USAGE ON SCHEMA ARCH_DEMO_DB.CURATED TO ROLE ANALYST_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA ARCH_DEMO_DB.CURATED TO ROLE ANALYST_ROLE;




-- ---------- Demonstrate layer behaviors ----------
-- Compute isolation: BI queries run on a different warehouse over the SAME storage
USE WAREHOUSE BI_WH;
SELECT * FROM ARCH_DEMO_DB.CURATED.SALES_BY_REGION ORDER BY MONTH DESC LIMIT 10;



-- Cloud services: metadata-only answer (no warehouse compute needed)
SELECT COUNT(*) FROM ARCH_DEMO_DB.RAW.ORDERS;



-- Result cache: re-run the same query and it returns instantly
SELECT * FROM ARCH_DEMO_DB.CURATED.SALES_BY_REGION ORDER BY MONTH DESC LIMIT 10;


-- Time Travel (run after ~60 seconds have passed since the insert)
SELECT COUNT(*) FROM ARCH_DEMO_DB.RAW.ORDERS AT (OFFSET => -60);



-- Micro-partition / clustering info
SELECT SYSTEM$CLUSTERING_INFORMATION('ARCH_DEMO_DB.RAW.ORDERS');


-- Elastic compute: resize the warehouse on demand
ALTER WAREHOUSE ETL_WH SET WAREHOUSE_SIZE = 'MEDIUM';
ALTER WAREHOUSE ETL_WH SET WAREHOUSE_SIZE = 'SMALL';



