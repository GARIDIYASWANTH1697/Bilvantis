------------------------------------------------------------
-- 1. STANDARD STREAM (tracks INSERT, UPDATE, DELETE)
------------------------------------------------------------
CREATE OR REPLACE STREAM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_STREAM
ON TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11;

------------------------------------------------------------
-- 2. APPEND-ONLY STREAM (tracks INSERTs only)
------------------------------------------------------------
CREATE OR REPLACE STREAM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_APPEND_STREAM
ON TABLE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11
APPEND_ONLY = TRUE;

SHOW STREAMS IN SCHEMA COMPANY_DBS.EMPLOYEE_SCHEMA;

------------------------------------------------------------
