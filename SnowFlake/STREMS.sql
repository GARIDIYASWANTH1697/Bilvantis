DELETE FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11 WHERE ID = 903;

------------------------------------------------------------
-- 4. INSPECT CHANGES (querying does NOT consume the stream)
------------------------------------------------------------
SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_STREAM;
-- Metadata columns: METADATA$ACTION (INSERT/DELETE),
--                   METADATA$ISUPDATE (TRUE for update pairs),
--                   METADATA$ROW_ID

SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_APPEND_STREAM;

SELECT SYSTEM$STREAM_HAS_DATA('COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_STREAM');

------------------------------------------------------------
-- 5. CONSUME STREAM: audit/history table (DML advances the offset)
------------------------------------------------------------
CREATE TABLE IF NOT EXISTS COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_AUDIT (
  ID NUMBER, NAME VARCHAR(50), DEPARTMENT VARCHAR(50), SALARY NUMBER(10,2),
  ACTION VARCHAR(10), IS_UPDATE BOOLEAN,
  CHANGED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

INSERT INTO COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_AUDIT (ID, NAME, DEPARTMENT, SALARY, ACTION, IS_UPDATE)
SELECT ID, NAME, DEPARTMENT, SALARY, METADATA$ACTION, METADATA$ISUPDATE
FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_STREAM;

-- Stream is now empty
SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_STREAM;

------------------------------------------------------------
-- 6. CONSUME STREAM: MERGE into a target (CDC sync)
------------------------------------------------------------
CREATE TABLE IF NOT EXISTS COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_TARGET
  LIKE COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11;

MERGE INTO COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_TARGET t
USING (
  SELECT * FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_APPEND_STREAM
) s
ON t.ID = s.ID
WHEN MATCHED THEN UPDATE SET t.NAME = s.NAME, t.DEPARTMENT = s.DEPARTMENT, t.SALARY = s.SALARY
WHEN NOT MATCHED THEN INSERT (ID, NAME, DEPARTMENT, SALARY) VALUES (s.ID, s.NAME, s.DEPARTMENT, s.SALARY);

------------------------------------------------------------
-- 7. AUTOMATE: task runs only when the stream has data
------------------------------------------------------------
CREATE OR REPLACE TASK COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_AUDIT_TASK
  WAREHOUSE = COMPUTE_WH
  SCHEDULE = '5 MINUTE'
WHEN SYSTEM$STREAM_HAS_DATA('COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_STREAM')
AS
  INSERT INTO COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_AUDIT (ID, NAME, DEPARTMENT, SALARY, ACTION, IS_UPDATE)
  SELECT ID, NAME, DEPARTMENT, SALARY, METADATA$ACTION, METADATA$ISUPDATE
  FROM COMPANY_DBS.EMPLOYEE_SCHEMA.EMPLOYEES11_STREAM;

